#!/usr/bin/env python3
"""Generate explicit native constructors for source-contract regression tests.

This is a development helper. Generated tests run without Python.
"""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
SOURCES = "\n".join((ROOT / "src" / name).read_text() for name in ["frames.rs", "frame_payloads.rs"])

def balanced(source, opening):
    depth = 1
    i = opening + 1
    while depth:
        if source[i] == "{": depth += 1
        if source[i] == "}": depth -= 1
        i += 1
    return source[opening + 1:i - 1]

def split(source):
    result, start, depth = [], 0, 0
    for i, char in enumerate(source):
        if char in "(<[{": depth += 1
        if char in ")>]}": depth -= 1
        if char == "," and depth == 0:
            result.append(source[start:i].strip()); start = i + 1
    tail = source[start:].strip()
    if tail: result.append(tail)
    return [item for item in result if item]

structs = {}
for match in re.finditer(r"pub struct (\w+)(?:<[^>{]+>)?\s*\{", SOURCES):
    body = balanced(SOURCES, match.end() - 1)
    fields = []
    for field in split(body):
        found = re.search(r"pub(?:\([^)]*\))?\s+(\w+)\s*:\s*(.+)", field, flags=re.S)
        if found: fields.append((found[1], found[2].strip()))
    structs[match[1]] = fields

SPECIAL = {
    "String": "String::new()", "Value": "serde_json::Value::Null", "ChatRole": "ChatRole::User",
    "KeypadEntry": "KeypadEntry::Zero", "FileSourceType": "FileSourceType::Bytes", "ErrorCategory": "ErrorCategory::Unknown",
    "ToolChoice": "ToolChoice::Auto", "ToolSet": "ToolSet::NotGiven", "MessageContent": 'MessageContent::Text(String::new())',
    "ProcessorReference": 'ProcessorReference::Name("test".into())',
    "LocalAsyncCallback": "LocalAsyncCallback::new(|| async { Ok(()) })",
    "LocalResultCallback": "LocalResultCallback::new(|_| async { Ok(()) })",
    "LocalMessageTransform": "LocalMessageTransform::new(Ok)", "LocalObject": "LocalObject::new(())",
    "AudioRawFrame": "AudioRawFrame::new(vec![], 16000, 1).unwrap()",
    "DtmfSequence": '"123#".parse().unwrap()', "StartFrame": "StartFrame::default()",
}

def sample(ty):
    ty = re.sub(r"\s+", " ", ty).strip()
    if ty in SPECIAL: return SPECIAL[ty]
    if ty.startswith("Box<ServiceUpdateSettingsFrame<"): return "Box::default()"
    if ty.startswith("Box<"): return "Box::new(" + sample(ty[4:-1]) + ")"
    if ty.startswith("Option<"): return "None"
    if ty.startswith("Vec<"): return "vec![]"
    if ty.startswith("BTreeMap<"): return "std::collections::BTreeMap::new()"
    if ty.startswith("Setting<"): return "Setting::NotGiven"
    if ty.startswith("ServiceUpdateSettingsFrame<"): return "ServiceUpdateSettingsFrame::default()"
    if ty == "bool": return "false"
    if ty in ["f32", "f64"]: return "0.0"
    if ty in ["u8", "u16", "u32", "u64", "usize", "i8", "i16", "i32", "i64"]: return "0"
    if ty.startswith("("): return "(" + ", ".join(sample(part) for part in split(ty[1:-1])) + ")"
    if ty not in structs: raise ValueError(f"Missing native sample for {ty}")
    return ty + " { " + ", ".join(f"{name}: {sample(field)}" for name, field in structs[ty]) + " }"

start = SOURCES.index("pub enum FrameData {") + len("pub enum FrameData ")
variants = split(balanced(SOURCES, start))
rows = []
for variant in variants:
    name = re.match(r"\w+", variant)[0]
    rest = variant[len(name):].strip()
    if rest.startswith("("):
        expression = f"FrameData::{name}(" + ", ".join(sample(ty) for ty in split(rest[1:-1])) + ")"
    elif rest.startswith("{"):
        fields = [part.split(":", 1) for part in split(rest[1:-1])]
        expression = f"FrameData::{name} {{ " + ", ".join(f"{key}: {sample(ty)}" for key, ty in fields) + " }"
    else: expression = f"FrameData::{name}"
    rows.append(f'        ("{name}", {expression}),')
text = '''// Generated by scripts/generate_contract_examples.py; constructors are intentionally explicit.
use pipecat_core::*;

#[test]
fn every_native_variant_matches_the_python_source_priority_and_interruptibility() {
    let fixture: serde_json::Value = serde_json::from_str(include_str!("fixtures/python_frame_contract.json")).unwrap();
    let classes = fixture["classes"].as_array().unwrap();
    let examples: Vec<(&str, FrameData)> = vec![
''' + "\n".join(rows) + '''
    ];
    assert_eq!(examples.len(), FRAME_CONTRACTS.len());
    let mut represented = std::collections::BTreeSet::new();
    for (variant, data) in examples {
        let contract = FRAME_CONTRACTS.iter().find(|contract| contract.rust_variant == variant).unwrap();
        assert_eq!(data.source_class_name(), contract.source_class);
        let source = classes.iter().find(|source| source["name"] == contract.source_class).unwrap();
        let priority = match source["priority"].as_str().unwrap() {
            "start" => FramePriority::Start, "system" => FramePriority::System, "normal" => FramePriority::Normal,
            other => panic!("unknown source priority {other}"),
        };
        let expected_interruptible = source["interruptible"].as_bool().unwrap();
        assert_eq!(data.priority(), priority, "priority of {variant}");
        let frame = Frame::new(data);
        assert_eq!(frame.interruptible, expected_interruptible, "interruptibility of {variant}");
        assert!(frame.name.starts_with(contract.source_class));
        represented.insert(contract.source_class);
    }
    for source in classes {
        if source["frame"] == true {
            let name = source["name"].as_str().unwrap();
            assert!(represented.contains(name), "missing source frame class {name}");
        }
    }
}
'''
(ROOT / "tests/native_contract_examples.rs").write_text(text)
print(f"Generated {len(rows)} native variant constructors")
